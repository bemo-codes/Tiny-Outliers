export function generateInitialResources(): HospitalResource[] {
  const list: HospitalResource[] = [];
  const now = Date.now();
  let count = 1;

  const templates = [
    { type: 'bed' as const, name: 'ICU Bed with Invasive Monitoring', cat: 'Critical Care', total: 20, avail: 6, unit: 'beds', attrs: { bed_type: 'ICU' } },
    { type: 'bed' as const, name: 'Emergency Resuscitation Bay', cat: 'Emergency Room', total: 12, avail: 3, unit: 'bays', attrs: { bed_type: 'ED_Bay' } },
    { type: 'ventilator' as const, name: 'High-Frequency ICU Ventilator', cat: 'Respiratory', total: 15, avail: 5, unit: 'units', attrs: { invasive: true } },
    { type: 'oxygen' as const, name: 'Liquid Medical Oxygen Bulk Reserve', cat: 'Life Support', total: 5000, avail: 3800, unit: 'liters', attrs: { purity: 99.5 } },
    { type: 'blood' as const, name: 'O-Negative Universal PRBC', cat: 'Blood Bank', total: 24, avail: 8, unit: 'units', attrs: { blood_group: 'O-' } },
    { type: 'medicine' as const, name: 'Tenecteplase / Alteplase (tPA)', cat: 'Thrombolytics', total: 10, avail: 4, unit: 'vials', attrs: { medicine_name: 'Tenecteplase', strength: '40mg' } },
    { type: 'operating_theatre' as const, name: 'Emergency Trauma Suite 1', cat: 'Surgical Suites', total: 2, avail: 1, unit: 'theatres', attrs: { ot_type: 'Trauma_L1' } },
    { type: 'equipment' as const, name: 'Point-of-Care Ultrasound (POCUS/FAST)', cat: 'Diagnostic', total: 6, avail: 4, unit: 'devices', attrs: { device: 'Ultrasound' } },
  ];

  for (const h of INITIAL_HOSPITALS) {
    for (const t of templates) {
      let avail = t.avail;
      let status: HospitalResource['availability_status'] = avail > 2 ? 'available' : avail > 0 ? 'limited' : 'unavailable';
      let ageMinutes = 4;

      // Scenario condition triggers
      if (h.id === 'hosp-004' && t.type === 'bed' && t.name.includes('ICU')) {
        avail = 0;
        status = 'unavailable';
      }
      if (h.id === 'hosp-007' || h.id === 'hosp-009') {
        ageMinutes = 45; // Stale scenario (> 10m threshold)
      }
      if (h.id === 'hosp-004' && t.type === 'medicine') {
        avail = 0;
        status = 'unavailable';
      }

      const verifiedAt = new Date(now - ageMinutes * 60 * 1000).toISOString();

      list.push({
        id: `res-${String(count++).padStart(3, '0')}`,
        hospital_id: h.id,
        resource_type: t.type,
        resource_name: t.name,
        category: t.cat,
        available_quantity: avail,
        total_quantity: t.total,
        unit: t.unit,
        availability_status: status,
        attributes: t.attrs,
        last_verified_at: verifiedAt,
        created_at: new Date(now - 86400000).toISOString(),
        updated_at: verifiedAt,
        is_fresh: ageMinutes <= 10,
        freshness_age_minutes: ageMinutes,
      });
    }
  }
  return list;
}

